use crate::studio::Language;
use std::cell::Cell;
thread_local! { static LANGUAGE:Cell<Language>=const {Cell::new(Language::French)}; }
pub fn set(language: Language) {
    LANGUAGE.set(language);
}
pub fn pair<'a>(fr: &'a str, en: &'a str) -> &'a str {
    if LANGUAGE.get() == Language::English {
        en
    } else {
        fr
    }
}
pub fn t(text: &str) -> String {
    if LANGUAGE.get() == Language::French {
        return text.into();
    }
    for (fr, en) in TEXT {
        if text == *fr {
            return (*en).into();
        }
        if text == fr.to_uppercase() {
            return en.to_uppercase();
        }
    }
    text.into()
}
