mod tests {
    use super::*;
    #[test]
    fn labels_translate_without_changing_user_content() {
        set(Language::English);
        assert_eq!(t("Schéma"), "Graph");
        assert_eq!(t("BIBLIOTHÈQUE DE BLOCS"), "BLOCK LIBRARY");
        assert_eq!(t("My DUT"), "My DUT");
        set(Language::French);
        assert_eq!(t("Schéma"), "Schéma");
    }
}
